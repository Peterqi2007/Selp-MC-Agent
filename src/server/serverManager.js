'use strict';

/**
 * Headless Minecraft server bootstrap.
 *
 * PCL2 is a *client* launcher: it can start a game window but it cannot host a
 * dedicated server. For an unattended agent we therefore build the server side
 * ourselves from the same Mojang artifacts PCL already trusts, and keep PCL for
 * the interactive client side (`npm run pcl:client`).
 *
 * This module: resolves the vanilla server jar for the configured version,
 * downloads + sha1-verifies it, writes eula.txt / server.properties, and can
 * spawn the server as a managed child process.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { spawn } = require('child_process');
const { Logger } = require('../util/logger');

const MANIFEST_URL = 'https://launchermeta.mojang.com/mc/game/version_manifest_v2.json';
const VERSION_MANIFEST_FALLBACK = 'https://piston-meta.mojang.com/mc/game/version_manifest_v2.json';

async function fetchJson(url) {
  const res = await fetch(url, { redirect: 'follow' });
  if (!res.ok) throw new Error(`GET ${url} -> HTTP ${res.status}`);
  return res.json();
}

async function download(url, dest, expectedSha1, log) {
  if (fs.existsSync(dest) && expectedSha1) {
    const current = sha1File(dest);
    if (current === expectedSha1) {
      log.info(`cached ok: ${path.basename(dest)}`);
      return dest;
    }
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  const tmp = `${dest}.part`;
  log.info(`downloading ${url}`);
  const res = await fetch(url, { redirect: 'follow' });
  if (!res.ok) throw new Error(`GET ${url} -> HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  fs.writeFileSync(tmp, buf);
  if (expectedSha1) {
    const got = sha1File(tmp);
    if (got !== expectedSha1) {
      fs.unlinkSync(tmp);
      throw new Error(`sha1 mismatch for ${path.basename(dest)}: expected ${expectedSha1}, got ${got}`);
    }
  }
  fs.renameSync(tmp, dest);
  log.info(`saved ${path.basename(dest)} (${(buf.length / 1048576).toFixed(1)} MiB)`);
  return dest;
}

function sha1File(file) {
  const hash = crypto.createHash('sha1');
  hash.update(fs.readFileSync(file));
  return hash.digest('hex');
}

/** Resolve the official server download descriptor for a Minecraft version. */
async function resolveServerArtifact(mcVersion, log = new Logger('server')) {
  let manifest;
  try {
    manifest = await fetchJson(MANIFEST_URL);
  } catch (err) {
    log.warn(`primary manifest failed (${err.message}), trying fallback`);
    manifest = await fetchJson(VERSION_MANIFEST_FALLBACK);
  }
  const entry = (manifest.versions || []).find((v) => v.id === mcVersion);
  if (!entry) throw new Error(`Minecraft version ${mcVersion} not found in Mojang manifest`);
  const detail = await fetchJson(entry.url);
  const server = detail.downloads && detail.downloads.server;
  if (!server) throw new Error(`Version ${mcVersion} has no server download (snapshot or client-only?)`);
  return {
    mcVersion,
    url: server.url,
    sha1: server.sha1,
    size: server.size,
    javaVersion: detail.javaVersion ? detail.javaVersion.majorVersion : null,
    clientMappings: detail.downloads.client_mappings ? detail.downloads.client_mappings.url : null
  };
}

function writeEula(serverDir) {
  const file = path.join(serverDir, 'eula.txt');
  const content = '# Generated by minecraft-survival-agent - indicates agreement to https://aka.ms/MinecraftEULA\neula=true\n';
  if (!fs.existsSync(file) || !/eula\s*=\s*true/i.test(fs.readFileSync(file, 'utf8'))) {
    fs.writeFileSync(file, content, 'utf8');
  }
}

function writeServerProperties(serverDir, srv) {
  const file = path.join(serverDir, 'server.properties');
  const props = {
    'allow-cheats': srv.allowCheats !== false,
    'allow-flight': true,
    'allow-nether': true,
    difficulty: srv.difficulty || 'normal',
    'enable-command-block': true,
    'enable-jmx-monitoring': false,
    'enable-query': false,
    'enable-rcon': false,
    'enforce-secure-profile': false,
    'force-gamemode': false,
    gamemode: srv.gamemode || 'survival',
    'generate-structures': true,
    'hardcore': false,
    'level-name': srv.levelName || 'agent-world',
    'level-seed': srv.levelSeed || '',
    'level-type': 'minecraft\\:normal',
    'max-players': srv.maxPlayers || 8,
    'motd': srv.motd || 'Mineflayer Survival Agent Lab',
    'network-compression-threshold': 256,
    'online-mode': srv.onlineMode === true,
    'op-permission-level': 4,
    'player-idle-timeout': 0,
    'prevent-proxy-connections': false,
    pvp: srv.pvp === true,
    'server-ip': srv.serverIp || '',
    'server-port': srv.port || 25565,
    'simulation-distance': srv.simulationDistance || 8,
    'spawn-animals': true,
    'spawn-monsters': true,
    'spawn-npcs': true,
    'spawn-protection': srv.spawnProtection || 0,
    'sync-chunk-writes': false,
    'view-distance': srv.viewDistance || 10,
    'white-list': false
  };
  const body = Object.entries(props)
    .map(([k, v]) => `${k}=${v === true ? 'true' : v === false ? 'false' : v}`)
    .join('\n');
  fs.writeFileSync(file, `# Generated by minecraft-survival-agent\n${body}\n`, 'utf8');
  return file;
}

/**
 * Prepare runtime/server so it can be started: jar downloaded, eula + properties written.
 * @returns {Promise<{serverDir:string, jar:string, artifact:object}>}
 */
async function prepareServer(cfg, log = new Logger('server')) {
  const serverDir = cfg.paths.server;
  fs.mkdirSync(serverDir, { recursive: true });
  const artifact = await resolveServerArtifact(cfg.server.mcVersion, log);
  const jar = path.join(serverDir, `server-${cfg.server.mcVersion}.jar`);
  await download(artifact.url, jar, artifact.sha1, log);
  writeEula(serverDir);
  writeServerProperties(serverDir, cfg.server);
  fs.writeFileSync(
    path.join(serverDir, 'agent-server.json'),
    JSON.stringify({ ...artifact, port: cfg.server.port, preparedAt: new Date().toISOString() }, null, 2)
  );
  log.info(`server ready: ${serverDir} (java ${artifact.javaVersion || '17+'})`);
  return { serverDir, jar, artifact };
}

/** Server banner line, e.g. `[12:00:00] [Server thread/INFO]: Done (7.031s)! For help, type "help"`. */
const READY_RE = /Done \([\d.]+s\)! For help, type "help"/i;

/** Fatal lines that mean the process will never reach the ready banner. */
const START_FAIL_RE = /You need to agree to the EULA|Failed to start the minecraft server/i;

/** Shared JVM flags for both the vanilla and the Forge launch path. */
function memoryArgs(heap) {
  return [
    `-Xms${Math.min(512, heap)}M`,
    `-Xmx${heap}M`,
    '-XX:+UseG1GC',
    '-Dfile.encoding=UTF-8',
    '-Djava.net.preferIPv4Stack=true'
  ];
}

/**
 * Spawn a java dedicated-server process and resolve `ready` once its log shows the
 * `Done (…)!` banner. Vanilla and Forge both use this so they return an identical shape.
 *
 * @param {{java:string, args:string[], cwd:string, logFile:string, log:object,
 *          readyRe?:RegExp, failRe?:RegExp}} spec
 * @returns {{proc: import('child_process').ChildProcess, ready: Promise<void>, logFile: string,
 *            command: (cmd:string)=>boolean, stop: (timeoutMs?:number)=>Promise<void>}}
 */
function spawnServerProcess({ java, args, cwd, logFile, log, readyRe = READY_RE, failRe = START_FAIL_RE }) {
  const stream = fs.createWriteStream(logFile, { flags: 'a' });
  log.info(`starting server: ${java} ${args.join(' ')}`);
  log.info(`server log -> ${logFile}`);

  const proc = spawn(java, args, { cwd, windowsHide: true, stdio: ['pipe', 'pipe', 'pipe'] });

  let buffer = '';
  let readyResolve;
  let readyReject;
  const ready = new Promise((resolve, reject) => {
    readyResolve = resolve;
    readyReject = reject;
  });
  let settled = false;

  const handle = (chunk) => {
    const text = chunk.toString();
    stream.write(text);
    buffer += text;
    const lines = buffer.split(/\r?\n/);
    buffer = lines.pop() || '';
    for (const line of lines) {
      if (!line.trim()) continue;
      log.info(`[mc] ${line}`);
      if (!settled && readyRe.test(line)) {
        settled = true;
        readyResolve();
      }
      if (!settled && failRe && failRe.test(line)) {
        settled = true;
        readyReject(new Error(line));
      }
    }
  };

  proc.stdout.on('data', handle);
  proc.stderr.on('data', handle);
  proc.on('exit', (code) => {
    log.warn(`server exited with code ${code}`);
    stream.end();
    if (!settled) {
      settled = true;
      readyReject(new Error(`server exited before becoming ready (code ${code})`));
    }
  });

  return {
    proc,
    ready,
    logFile,
    /** Run a command in the server console (op, time set day, gamerule, ...). */
    command(cmd) {
      if (!proc.stdin || proc.stdin.destroyed) {
        log.warn(`cannot send "${cmd}": server stdin is closed`);
        return false;
      }
      log.info(`console> ${cmd}`);
      try {
        proc.stdin.write(`${cmd}\n`);
        return true;
      } catch (err) {
        log.warn(`console command failed: ${err.message}`);
        return false;
      }
    },
    stop: (timeoutMs = 15000) =>
      new Promise((resolve) => {
        if (proc.exitCode !== null) return resolve();
        const kill = setTimeout(() => {
          log.warn('server did not stop in time, killing');
          proc.kill('SIGKILL');
        }, timeoutMs);
        proc.once('exit', () => {
          clearTimeout(kill);
          resolve();
        });
        try {
          proc.stdin.write('stop\n');
        } catch {
          proc.kill();
        }
      })
  };
}

/**
 * Start the dedicated vanilla server and resolve once it reports ready.
 * @returns {Promise<{proc: import('child_process').ChildProcess, ready: Promise<void>, stop: Function, logFile: string}>}
 */
function startServer(cfg, options = {}) {
  const log = options.log || new Logger('server');
  const serverDir = cfg.paths.server;
  const jar = options.jar || path.join(serverDir, `server-${cfg.server.mcVersion}.jar`);
  const java = options.java;
  if (!java) throw new Error('startServer requires a java executable (options.java)');
  if (!fs.existsSync(jar)) throw new Error(`server jar missing: ${jar} (run: npm run server:setup)`);

  const heap = options.maxHeapMb || cfg.server.maxHeapMb || 2048;
  const args = [...memoryArgs(heap), '-jar', jar, 'nogui'];

  fs.mkdirSync(cfg.paths.logs, { recursive: true });
  const logFile = path.join(cfg.paths.logs, `server-${Date.now()}.log`);
  return spawnServerProcess({ java, args, cwd: serverDir, logFile, log });
}

/**
 * Reject with `message` if `promise` has not settled within `ms`.
 * The timer is always cleared, so a satisfied race never keeps node alive for the
 * remainder of the timeout.
 */
function withTimeout(promise, ms, message) {
  let timer;
  return Promise.race([
    promise,
    new Promise((_, reject) => {
      timer = setTimeout(() => reject(new Error(message)), ms);
    })
  ]).finally(() => clearTimeout(timer));
}

/** Simple TCP probe used to wait for the port to accept connections. */
function waitForPort(host, port, timeoutMs = 120000, intervalMs = 1000) {
  const net = require('net');
  const deadline = Date.now() + timeoutMs;
  return new Promise((resolve, reject) => {
    const attempt = () => {
      const socket = net.connect({ host, port });
      socket.setTimeout(2000);
      socket.once('connect', () => {
        socket.destroy();
        resolve(true);
      });
      const fail = () => {
        socket.destroy();
        if (Date.now() > deadline) reject(new Error(`port ${host}:${port} not open after ${timeoutMs}ms`));
        else setTimeout(attempt, intervalMs);
      };
      socket.once('error', fail);
      socket.once('timeout', fail);
    };
    attempt();
  });
}

